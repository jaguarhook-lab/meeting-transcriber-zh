# ── 我的預設（檔案）──────────────────────────────────────────────────
def user_dir() -> Path:
    return base_dir() / "提示詞"


def _path(name: str) -> Path:
    return user_dir() / f"{name}.md"


def _meta_path() -> Path:
    return user_dir() / "_原廠版本.json"


def _hash(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()[:16]


def load(name: str) -> tuple:
    """→ (範本文字, 來源「我的預設」／「原廠預設」)。"""
    p = _path(name)
    if p.exists():
        try:
            return p.read_text(encoding="utf-8").replace("\r\n", "\n"), "我的預設"
        except OSError:
            pass
    return FACTORY[name], "原廠預設"


def check(name: str, text: str) -> list:
    """存檔前檢查 → 問題清單（空＝可存）。"""
    probs = []
    for f, desc in FIELDS[name].items():
        if desc.startswith("★") and "{" + f + "}" not in text:
            probs.append(f"不能刪掉欄位「{{{f}}}」：{desc[2:]}")
    for t in REQUIRED_TEXT.get(name, []):
        if t not in text:
            probs.append(f"不能刪掉「{t}」：程式要靠 AI 回傳的 JSON 格式讀回結果")
    unknown = sorted({m for m in re.findall(r"\{([^{}\s\"]{1,12})\}", text)} - set(FIELDS[name]))
    if unknown:
        probs.append("這個範本沒有這些欄位（會原樣送出）：" + "、".join("{" + u + "}" for u in unknown))
    return probs


def _backup(p: Path) -> Path | None:
    if not p.exists():
        return None
    bk = user_dir() / "備份"
    bk.mkdir(parents=True, exist_ok=True)
    dst = bk / f"{p.stem}_{dt.datetime.now():%Y%m%d_%H%M%S}.md"
    shutil.copy2(p, dst)
    return dst


def save_user(name: str, text: str) -> Path:
    """存成我的預設（舊版先備份），並記下當時的原廠版本，之後才知道原廠有沒有更新。"""
    user_dir().mkdir(parents=True, exist_ok=True)
    p = _path(name)
    _backup(p)
    p.write_text(text.replace("\r\n", "\n"), encoding="utf-8")
    meta = _meta()
    meta[name] = dict(base=_hash(FACTORY[name]), factory_version=FACTORY_VERSION, saved=dt.datetime.now().isoformat(timespec="seconds"))
    _meta_path().write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")
    return p


def reset(name: str) -> Path | None:
    """還原原廠預設：我的預設移到備份（不刪），之後就用原廠版。"""
    p = _path(name)
    if not p.exists():
        return None
    bk = user_dir() / "備份"
    bk.mkdir(parents=True, exist_ok=True)
    dst = bk / f"{p.stem}_{dt.datetime.now():%Y%m%d_%H%M%S}_還原前.md"
    shutil.move(str(p), str(dst))                        # 移到備份（不刪），之後就改用原廠版
    meta = _meta()
    meta.pop(name, None)
    _meta_path().write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")
    return dst


def _meta() -> dict:
    try:
        return json.loads(_meta_path().read_text(encoding="utf-8"))
    except Exception:
        return {}


def factory_updated(name: str) -> bool:
    """有「我的預設」，且建立時依據的原廠版本和現在的原廠版本不同。"""
    m = _meta().get(name)
    return bool(_path(name).exists() and m and m.get("base") != _hash(FACTORY[name]))


# ── 組成提示 ─────────────────────────────────────────────────────────
def fill(text: str, values: dict) -> str:
    """只替換已知欄位；其他大括號（例如 JSON 範例）原樣保留。"""
    return FIELD_RE.sub(lambda m: str(values.get(m.group(1), m.group(0))), text)


def build(name: str, values: dict, override: str | None = None) -> str:
    """override＝本次送出時使用者改過的範本。寫作規則自動填入。"""
    text = override if override is not None else load(name)[0]
    v = dict(values)
    if "寫作規則" in FIELDS.get(name, {}) and "寫作規則" not in v:
        v["寫作規則"] = load("寫作規則")[0]
    if "長期記憶" in FIELDS.get(name, {}) and "長期記憶" not in v:   # 長期記憶自動帶入（沒有記憶時是空白）
        import memory
        v["長期記憶"] = memory.prompt_block()
    return fill(text, v)
